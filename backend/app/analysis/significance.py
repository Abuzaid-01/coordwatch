"""
Phase D2: Null-Model Permutation Significance Testing and Benjamini-Hochberg FDR Control.

Calculates empirical p-values for detected coordination clusters by comparing observed
timing and text synchronization against shuffled-null permutations.
Applies Benjamini-Hochberg False Discovery Rate (FDR) control across all topic clusters.
"""

from datetime import datetime
import math
import random
from typing import Any, Dict, List, Optional, Tuple


def _parse_ts(iso_str: Optional[str]) -> float:
    if not iso_str:
        return 0.0
    try:
        return datetime.fromisoformat(iso_str.replace("Z", "+00:00")).timestamp()
    except Exception:
        return 0.0


def compute_cluster_significance(
    cluster_dids: List[str],
    cluster_score: float,
    all_topic_posts: List[Dict[str, Any]],
    n_permutations: int = 100,
    seed: int = 42,
) -> Dict[str, Any]:
    """
    Computes empirical p-value for a cluster by testing whether the cluster's
    co-posting burst tightness and concentration could arise under random author assignment.

    Null Hypothesis (H0): Posts are generated by independent authors; timestamp distribution
    is independent of author identity.
    """
    def not_tested(reason: str) -> Dict[str, Any]:
        return {
            "p_value": None,
            "status": "not_tested",
            "reason": reason,
            "stat_observed": 0.0,
            "stat_null_mean": 0.0,
            "stat_null_std": 0.0,
            "n_permutations": 0,
            "cluster_score_used": float(cluster_score or 0.0),
            "significant": False,
        }

    if len(cluster_dids) < 2 or not all_topic_posts or cluster_score <= 0:
        return not_tested("too few members or no posts")

    cluster_set = set(cluster_dids)
    observed_cluster_posts = [p for p in all_topic_posts if p.get("did") in cluster_set]
    if len(observed_cluster_posts) < 2:
        return not_tested("fewer than two posts from cluster members")

    # Extract timestamps
    timed_posts = []
    for p in all_topic_posts:
        ts = _parse_ts(p.get("created_at") or p.get("createdAt"))
        if ts > 0:
            timed_posts.append((ts, p.get("did")))

    if len(timed_posts) < len(cluster_dids):
        return not_tested("fewer timestamps than cluster members")

    timed_posts.sort(key=lambda x: x[0])
    all_timestamps = [t[0] for t in timed_posts]
    all_dids = [t[1] for t in timed_posts]

    # Observed test statistic: Pairwise bursts within 60s among cluster members
    def calculate_burst_stat(dids_sequence: List[str], timestamps: List[float], target_set: set) -> float:
        burst_count = 0
        n = len(timestamps)
        for i in range(n):
            if dids_sequence[i] not in target_set:
                continue
            t_i = timestamps[i]
            for j in range(i + 1, n):
                delta = timestamps[j] - t_i
                if delta > 90.0:  # 90s burst window
                    break
                if dids_sequence[j] in target_set and dids_sequence[j] != dids_sequence[i]:
                    burst_count += 1
        return float(burst_count)

    obs_stat = calculate_burst_stat(all_dids, all_timestamps, cluster_set)

    rng = random.Random(seed)
    null_stats: List[float] = []
    greater_count = 0

    shuffled_dids = list(all_dids)
    for _ in range(n_permutations):
        rng.shuffle(shuffled_dids)
        null_s = calculate_burst_stat(shuffled_dids, all_timestamps, cluster_set)
        null_stats.append(null_s)
        if null_s >= obs_stat:
            greater_count += 1

    empirical_p = (greater_count + 1) / (n_permutations + 1)
    mean_null = sum(null_stats) / max(1, len(null_stats))
    variance = sum((s - mean_null) ** 2 for s in null_stats) / max(1, len(null_stats))
    std_null = math.sqrt(variance)

    return {
        "p_value": round(empirical_p, 4),
        "status": "tested",
        "stat_observed": round(obs_stat, 2),
        "stat_null_mean": round(mean_null, 2),
        "stat_null_std": round(std_null, 2),
        "n_permutations": n_permutations,
        "cluster_score_used": float(cluster_score),
        "significant": empirical_p < 0.05,
    }


def apply_benjamini_hochberg_fdr(clusters: List[Dict[str, Any]], alpha: float = 0.05) -> List[Dict[str, Any]]:
    """
    Applies Benjamini-Hochberg only to clusters still labeled coordinated_inauthentic.
    Organic and benign clusters are not claims, so they do not increase m.
    Adds 'fdr_q_value' and 'fdr_significant' to each cluster dictionary.
    """
    if not clusters:
        return []

    # Only inauthentic claims enter the family of tests. Organic and benign
    # clusters are not discoveries, and counting them inflates m until a real
    # burst fails Benjamini-Hochberg.
    tested_indexes = [
        i for i, cl in enumerate(clusters)
        if cl.get("classification") == "coordinated_inauthentic"
        and (cl.get("significance") or {}).get("status") == "tested"
        and (cl.get("significance") or {}).get("p_value") is not None
    ]
    for i, cl in enumerate(clusters):
        if i not in tested_indexes:
            sig_obj = cl.get("significance") or {}
            sig_obj["fdr_q_value"] = None
            sig_obj["fdr_significant"] = False
            cl["significance"] = sig_obj

    if not tested_indexes:
        return clusters

    m = len(tested_indexes)
    indexed = sorted(
        tested_indexes,
        key=lambda i: clusters[i].get("significance", {}).get("p_value", 1.0),
    )

    q_values = {i: 1.0 for i in tested_indexes}
    for rank_idx, orig_idx in enumerate(indexed):
        rank = rank_idx + 1
        p_val = clusters[orig_idx].get("significance", {}).get("p_value", 1.0)
        q_values[orig_idx] = min(1.0, (p_val * m) / rank)

    min_q = 1.0
    for orig_idx in reversed(indexed):
        min_q = min(min_q, q_values[orig_idx])
        q_values[orig_idx] = round(min_q, 4)

    for orig_idx in tested_indexes:
        q = q_values[orig_idx]
        sig_obj = clusters[orig_idx].get("significance") or {}
        sig_obj["fdr_q_value"] = q
        sig_obj["fdr_significant"] = q <= alpha
        clusters[orig_idx]["significance"] = sig_obj

    return clusters


def apply_detection_decisions(clusters: List[Dict[str, Any]], alpha: float = 0.05) -> List[Dict[str, Any]]:
    """FDR q-values, then withhold an inauthentic label that did not survive them.

    Benign clusters stay benign. A cluster that was not tested cannot carry
    an inauthentic claim.
    """
    clusters = apply_benjamini_hochberg_fdr(clusters, alpha=alpha)
    for cl in clusters:
        sig = cl.get("significance") or {}
        tested = sig.get("status") == "tested" and sig.get("p_value") is not None
        if cl.get("classification") == "coordinated_inauthentic" and (not tested or not sig.get("fdr_significant")):
            cl["classification"] = "insufficient_evidence"
            reasons = list(cl.get("reasons") or [])
            reasons.append(
                "Inauthentic label withheld: the permutation test did not pass "
                "Benjamini-Hochberg FDR control at alpha 0.05."
            )
            cl["reasons"] = reasons
    return clusters

